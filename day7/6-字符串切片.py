num_str = "0123456789"
# 指定的区间属于左闭右开型[开始索引, 结束索引)
# 1.截取从2~5位置的字符串
print(num_str[2:6])
# 2.截取从2~末尾的字符串
print(num_str[2:])
# 3.截取从开始~5位置的字符串
print(num_str[:6])
# 4.截取完整的字符串
print(num_str[:])
# 5.从开始位置，每隔一个字符截取字符串
print(num_str[::2])#加步长
# 6.从索引1开始，每隔一个取一个
print(num_str[1::2])
# 7.截取从2~末尾 -1的字符串
print(num_str[2:-1])#-1表示倒数第一个字符
# 8.截取字符串末尾两个字符
print(num_str[-2:])#-2，左闭右开

# 9.字符串的逆序（面试题）
print(num_str[::-1])








